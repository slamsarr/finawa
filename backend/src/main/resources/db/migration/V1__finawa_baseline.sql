-- =============================================================================
-- FINAWA baseline schema — generated from JPA entities
-- =============================================================================

-- -----------------------------------------------------------------------------
-- finawa_profile  (ProfileEntity + Auditable)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS finawa_profile (
    prf_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prf_name        VARCHAR(255) UNIQUE,
    prf_description VARCHAR(255),
    created_by      VARCHAR(255),
    created_date    TIMESTAMP,
    modified_by     VARCHAR(255),
    modified_date   TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- profile_permission  (@ElementCollection on ProfileEntity)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS profile_permission (
    prf_id     BIGINT      NOT NULL REFERENCES finawa_profile (prf_id),
    permission VARCHAR(255) NOT NULL,
    PRIMARY KEY (prf_id, permission)
);

-- -----------------------------------------------------------------------------
-- finawa_user  (UserEntity + Auditable)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS finawa_user (
    usr_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usr_login           VARCHAR(255) UNIQUE,
    usr_password        VARCHAR(255),
    usr_first_attempt   BOOLEAN DEFAULT FALSE,
    usr_active          BOOLEAN,
    usr_linked_profile  BIGINT REFERENCES finawa_profile (prf_id),
    created_by          VARCHAR(255),
    created_date        TIMESTAMP,
    modified_by         VARCHAR(255),
    modified_date       TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- finawa_token  (TokenEntity)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS finawa_token (
    id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token   VARCHAR(255),
    expired BOOLEAN,
    revoked BOOLEAN,
    usr_id  BIGINT REFERENCES finawa_user (usr_id)
);

-- -----------------------------------------------------------------------------
-- finawa_label  (LabelEntity + Auditable)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS finawa_label (
    lbl_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lbl_type        VARCHAR(255),
    lbl_name        VARCHAR(255),
    lbl_description VARCHAR(255),
    created_by      VARCHAR(255),
    created_date    TIMESTAMP,
    modified_by     VARCHAR(255),
    modified_date   TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- finawa_document  (DocumentEntity + Auditable)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS finawa_document (
    doc_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_usr_id             BIGINT REFERENCES finawa_user (usr_id),
    doc_name                 VARCHAR(255) UNIQUE,
    doc_stored_name          VARCHAR(255),
    doc_extension            VARCHAR(255),
    doc_size                 BIGINT,
    doc_description          VARCHAR(255),
    doc_date                 TIMESTAMP,
    doc_linked_document_type BIGINT REFERENCES finawa_label (lbl_id),
    doc_mark_delete          BOOLEAN,
    created_by               VARCHAR(255),
    created_date             TIMESTAMP,
    modified_by              VARCHAR(255),
    modified_date            TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- finawa_enterprise  (EnterpriseEntity + Auditable)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS finawa_enterprise (
    ent_id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ent_user_id              BIGINT REFERENCES finawa_user (usr_id),
    ent_name                 VARCHAR(255),
    ent_summary              VARCHAR(255),
    ent_region               VARCHAR(255),
    ent_turnover             BIGINT,
    ent_employees            BIGINT,
    ent_date                 TIMESTAMP,
    ent_linked_enterprise_type BIGINT REFERENCES finawa_label (lbl_id),
    ent_linked_sector_type   BIGINT REFERENCES finawa_label (lbl_id),
    created_by               VARCHAR(255),
    created_date             TIMESTAMP,
    modified_by              VARCHAR(255),
    modified_date            TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- finawa_alert  (AlertEntity + Auditable)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS finawa_alert (
    ale_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ale_message         TEXT,
    ale_date            TIMESTAMP,
    ale_read            BOOLEAN DEFAULT FALSE,
    ale_linked_priority BIGINT REFERENCES finawa_label (lbl_id),
    ale_linked_user     BIGINT REFERENCES finawa_user (usr_id),
    created_by          VARCHAR(255),
    created_date        TIMESTAMP,
    modified_by         VARCHAR(255),
    modified_date       TIMESTAMP
);

-- -----------------------------------------------------------------------------
-- finawa_journal  (JournalEntity — no Auditable, only created_date)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS finawa_journal (
    jnl_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    jnl_typeAction VARCHAR(255),
    jnle_adresse_ip VARCHAR(255),
    jnle_user_agent VARCHAR(512),
    jnle_user       VARCHAR(255),
    jnle_lgin       VARCHAR(255),
    method_http     VARCHAR(50),
    url             VARCHAR(1024),
    page            VARCHAR(512),
    query_string    TEXT,
    referer_page    VARCHAR(512),
    created_date    TIMESTAMP,
    data            TEXT,
    path            VARCHAR(255)
);

-- =============================================================================
-- FINAWA email verification token schema
-- =============================================================================

CREATE TABLE IF NOT EXISTS finawa_verification_token (
    tok_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tok_token           VARCHAR(255) NOT NULL UNIQUE,
    tok_user_id         BIGINT NOT NULL REFERENCES finawa_user (usr_id) ON DELETE CASCADE,
    tok_expiry_date     TIMESTAMP NOT NULL,
    tok_confirmed_date  TIMESTAMP,
    created_by          VARCHAR(255),
    created_date        TIMESTAMP,
    modified_by         VARCHAR(255),
    modified_date       TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_verification_token ON finawa_verification_token (tok_token);
CREATE INDEX IF NOT EXISTS idx_verification_user ON finawa_verification_token (tok_user_id);

-- =============================================================================
-- FINAWA password reset token schema
-- =============================================================================

CREATE TABLE IF NOT EXISTS finawa_password_reset_token (
    pwr_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pwr_token           VARCHAR(255) NOT NULL UNIQUE,
    pwr_user_id         BIGINT NOT NULL REFERENCES finawa_user (usr_id) ON DELETE CASCADE,
    pwr_expiry_date     TIMESTAMP NOT NULL,
    pwr_used_date       TIMESTAMP,
    created_by          VARCHAR(255),
    created_date        TIMESTAMP,
    modified_by         VARCHAR(255),
    modified_date       TIMESTAMP
);