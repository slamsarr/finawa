-- =============================================================================
-- FINAWA Dossier, Partner and Matching schema
-- =============================================================================

-- -----------------------------------------------------------------------------
-- finawa_dossier  (DossierEntity + Auditable)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS finawa_dossier (
    dos_id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dos_reference               VARCHAR(255) UNIQUE,
    dos_enterprise_id           BIGINT REFERENCES finawa_enterprise (ent_id),
    dos_linked_need_type        BIGINT REFERENCES finawa_label (lbl_id),
    dos_amount                  DECIMAL(19, 2),
    dos_duration_months         INTEGER,
    dos_purpose                 VARCHAR(500),
    dos_status                  VARCHAR(50),
    dos_score                   INTEGER,
    dos_submission_date         TIMESTAMP,
    dos_next_action             VARCHAR(255),
    dos_description             TEXT,
    dos_ca_valid                BOOLEAN DEFAULT FALSE,
    dos_ninea_provided          BOOLEAN DEFAULT FALSE,
    dos_guarantee_complete      BOOLEAN DEFAULT FALSE,
    created_by                  VARCHAR(255),
    created_date                TIMESTAMP,
    modified_by                 VARCHAR(255),
    modified_date               TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_dossier_reference ON finawa_dossier (dos_reference);
CREATE INDEX IF NOT EXISTS idx_dossier_enterprise ON finawa_dossier (dos_enterprise_id);
CREATE INDEX IF NOT EXISTS idx_dossier_status ON finawa_dossier (dos_status);

-- -----------------------------------------------------------------------------
-- finawa_partner  (PartnerEntity + Auditable)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS finawa_partner (
    prt_id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    prt_user_id                 BIGINT REFERENCES finawa_user (usr_id),
    prt_name                    VARCHAR(255),
    prt_type                    VARCHAR(100),
    prt_description             TEXT,
    prt_conditions              TEXT,
    prt_pricing                 VARCHAR(500),
    prt_min_amount              DECIMAL(19, 2),
    prt_max_amount              DECIMAL(19, 2),
    prt_min_duration_months     INTEGER,
    prt_max_duration_months     INTEGER,
    prt_interest_rate           DECIMAL(5, 2),
    prt_score                   INTEGER,
    prt_active                  BOOLEAN DEFAULT TRUE,
    prt_linked_partner_type     BIGINT REFERENCES finawa_label (lbl_id),
    created_by                  VARCHAR(255),
    created_date                TIMESTAMP,
    modified_by                 VARCHAR(255),
    modified_date               TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_partner_user ON finawa_partner (prt_user_id);
CREATE INDEX IF NOT EXISTS idx_partner_type ON finawa_partner (prt_type);
CREATE INDEX IF NOT EXISTS idx_partner_active ON finawa_partner (prt_active);

-- -----------------------------------------------------------------------------
-- partner_zone  (Many-to-Many: Partner - Label for zones)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS partner_zone (
    prt_id     BIGINT NOT NULL REFERENCES finawa_partner (prt_id) ON DELETE CASCADE,
    lbl_id     BIGINT NOT NULL REFERENCES finawa_label (lbl_id) ON DELETE CASCADE,
    PRIMARY KEY (prt_id, lbl_id)
);

CREATE INDEX IF NOT EXISTS idx_partner_zone_prt ON partner_zone (prt_id);
CREATE INDEX IF NOT EXISTS idx_partner_zone_lbl ON partner_zone (lbl_id);

-- -----------------------------------------------------------------------------
-- partner_sector  (Many-to-Many: Partner - Label for sectors)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS partner_sector (
    prt_id     BIGINT NOT NULL REFERENCES finawa_partner (prt_id) ON DELETE CASCADE,
    lbl_id     BIGINT NOT NULL REFERENCES finawa_label (lbl_id) ON DELETE CASCADE,
    PRIMARY KEY (prt_id, lbl_id)
);

CREATE INDEX IF NOT EXISTS idx_partner_sector_prt ON partner_sector (prt_id);
CREATE INDEX IF NOT EXISTS idx_partner_sector_lbl ON partner_sector (lbl_id);

-- -----------------------------------------------------------------------------
-- finawa_matching  (MatchingEntity + Auditable)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS finawa_matching (
    mch_id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mch_dossier_id          BIGINT REFERENCES finawa_dossier (dos_id) ON DELETE CASCADE,
    mch_partner_id          BIGINT REFERENCES finawa_partner (prt_id) ON DELETE CASCADE,
    mch_score               DECIMAL(5, 2),
    mch_match_date          TIMESTAMP,
    mch_status              VARCHAR(50),
    mch_amount_suitable     BOOLEAN,
    mch_duration_suitable    BOOLEAN,
    mch_sector_suitable     BOOLEAN,
    mch_zone_suitable       BOOLEAN,
    mch_notes               TEXT,
    created_by              VARCHAR(255),
    created_date            TIMESTAMP,
    modified_by             VARCHAR(255),
    modified_date           TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_matching_dossier ON finawa_matching (mch_dossier_id);
CREATE INDEX IF NOT EXISTS idx_matching_partner ON finawa_matching (mch_partner_id);
CREATE INDEX IF NOT EXISTS idx_matching_status ON finawa_matching (mch_status);
CREATE INDEX IF NOT EXISTS idx_matching_score ON finawa_matching (mch_score);
